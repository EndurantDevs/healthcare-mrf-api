_BINDING_CONTRACT = "custom-import/source-binding/v1"
_CONNECTOR_KIND = "snowflake_bundle"
_BINDING_TABLE = "custom_import_source_binding_revision"
_DEFINITION_TABLE = "custom_import_definition_revision"
_EXECUTION_TABLE = "custom_import_execution"
_BINDING_IMMUTABLE_TRIGGER = "custom_import_source_binding_revision_immutable_row_guard"
_BINDING_TRUNCATE_TRIGGER = "custom_import_source_binding_revision_truncate_guard"
_EXECUTION_BINDING_GUARD = "guard_custom_import_execution_source_binding_revision"
_EXECUTION_BINDING_TRIGGER = "custom_import_execution_source_binding_revision_guard"
