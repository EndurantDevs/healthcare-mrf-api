    assert _statements(session) == [
        f'DROP TABLE "{ownership.schema_name}"."synthetic_child", "{ownership.schema_name}"."synthetic_parent" RESTRICT',
        f'DROP SCHEMA "{ownership.schema_name}"',
    ]


