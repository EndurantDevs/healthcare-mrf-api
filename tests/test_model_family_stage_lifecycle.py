@pytest.mark.asyncio
async def test_completion_finishes_all_indexes_and_constraints_before_set_checks(scoped_family_fixture):
    spec, ownership, catalog, session = scoped_family_fixture

    async def has_invalid_relationship(statement):
        statements = _statements(session)
        assert sum("PRIMARY KEY" in sql for sql in statements) == 2
        assert any("UNIQUE" in sql for sql in statements)
        assert any("synthetic_child_parent_idx" in sql for sql in statements)
        assert any("synthetic_child_id_check" in sql for sql in statements)
        assert "SELECT EXISTS" in str(statement) and "NOT EXISTS" in str(statement)
        return False

    session.scalar.side_effect = has_invalid_relationship
    await archive.complete_model_family_stage(session, spec, ownership, include_identity=True)
    catalog.sequences.assert_awaited_once_with(session, ownership.schema_oid, include_identity=True)
    assert session.scalar.await_count == 2
    assert all("FOREIGN KEY" not in statement and "TRIGGER" not in statement for statement in _statements(session))


