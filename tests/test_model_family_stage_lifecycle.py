@pytest.mark.asyncio
@pytest.mark.parametrize("operation", ("capture", "verify", "precreate", "complete", "cleanup"))
async def test_every_public_lifecycle_operation_requires_caller_transaction(scoped_family_fixture, operation):
    spec, ownership, catalog, session = scoped_family_fixture
    session.in_transaction = lambda: False
    function = {
        "capture": archive.capture_model_family_stage_ownership,
        "verify": archive.verify_model_family_stage_ownership,
        "precreate": archive.precreate_model_family_stage,
        "complete": archive.complete_model_family_stage,
        "cleanup": archive.cleanup_model_family_stage,
    }[operation]
    argument = ownership.dataset_id if operation in {"capture", "precreate"} else ownership
    with pytest.raises(archive.ReferenceFamilyArchiveError, match="caller transaction"):
        await function(session, spec, argument, include_identity=True)
    session.execute.assert_not_awaited()
    session.scalar.assert_not_awaited()
    catalog.schema.assert_not_awaited()
