def _statements(session):
    return [
        " ".join(str(call.args[0].compile(dialect=archive.postgresql.dialect())).split())
        for call in session.execute.await_args_list
    ]


@pytest.mark.asyncio
async def test_unregistered_family_precreates_ordinary_heaps_with_exact_identity_custody(scoped_family_fixture):
    spec, ownership, catalog, session = scoped_family_fixture
    assert spec.importer_id not in archive._SPECS
    observed = await archive.precreate_model_family_stage(session, spec, ownership.dataset_id, include_identity=True)
    assert observed == ownership
    statements = _statements(session)
    assert len(statements) == 3
    assert "GENERATED BY DEFAULT AS IDENTITY" in statements[2]
    assert all(
        fragment not in " ".join(statements)
        for fragment in ("PARTITION BY", "SERIAL", "PRIMARY KEY", "UNIQUE", "CHECK", "CREATE INDEX", "FOREIGN KEY")
    )
    assert all(model.__table__.schema == "synthetic_source" for model in spec.model_types)
    catalog.sequences.assert_awaited_once_with(session, ownership.schema_oid, include_identity=True)
    assert (
        await archive.verify_model_family_stage_ownership(session, spec, ownership, include_identity=True) == ownership
    )
    catalog.sequences.assert_awaited_with(session, ownership.schema_oid, include_identity=True)


