async def _make_candidate(connection, catalog, schema, *, run, dataset, old):
    tables_by_kind = {
        key: {"schema": schema, "name": name}
        for key, name in (("resource_input", "resource_input"), ("witness_input", "witness_input"))
    }
    resources = sorted(directory.PUBLIC_DIRECTORY_SEVEN_RESOURCES)
    metadata = {
        "source_ids": SOURCE_IDS,
        "expected_resources": resources,
        "selected_resources": resources,
        "resource_hash_contract": DEFAULT_RESOURCE_HASH_CONTRACT,
        "semantic_projection_as_of": "2026-01-01" if old else "2026-01-02",
    }
    binding_by_field = dict(
        contract=storage.NAMED_ISOLATED_CONTRACT,
        phase="loading",
        ordinal=5 if old else 0,
        resets={},
        identity=dict(dataset_id=dataset, endpoint_id="endpoint", acquisition_root_run_id=run, metadata=metadata),
        tables=tables_by_kind,
        storage=dict(catalog_schema=catalog, storage_schema=schema),
        auxiliary=None,
        relationship_sha256=None,
        admission=None,
    )
    name = storage_identifier(schema)
    await _create_candidate_fixture_tables(connection, name)
    await connection.execute(
        f"INSERT INTO {name}.{storage.HEADER} VALUES ($1,'endpoint',$2,$2,$3,false,NULL,$4::jsonb,$5::jsonb)",
        dataset,
        run,
        "failed" if old else "acquiring",
        json.dumps(metadata),
        json.dumps(binding_by_field),
    )
    return name


async def _checkpoint(connection, schema, kind, *, old, count, start_hash, payload=None):
    run, dataset, scope = (OLD_RUN, OLD_DATASET, "old-scope") if old else (NEW_RUN, NEW_DATASET, "new-scope")
    await connection.execute(
        f"INSERT INTO {schema}.{recovery._CHECKPOINT} VALUES ($1,$2,$3,$4,$5::json,$6,$6,NULL,$7,$8,"
        "CASE WHEN $9::bigint>0 THEN 'complete' ELSE 'active' END,$9,$9,'[]','{}',now(),now(),"
        "CASE WHEN $9>0 THEN now() END)",
        BASE,
        kind,
        scope,
        dataset,
        json.dumps(SOURCE_IDS),
        run,
        start_hash,
        payload,
        count,
    )


async def _prepare_checkpoint_fixture(connection, old_schema, new_schema):
    config = directory._build_partition_config(
        {
            "start": "2026-01-01T00:00:00Z",
            "end": "2026-02-01T00:00:00Z",
            "minimum_width_seconds": 1,
            "ceiling": 499,
        }
    )
    initialized = directory._new_last_updated_partition_plan(config)
    kind = "OrganizationAffiliation" + recovery._PARTITION
    start_hash = directory._last_updated_partition_start_hash("OrganizationAffiliation", config)
    await _checkpoint(
        connection,
        new_schema,
        kind,
        old=False,
        count=0,
        start_hash=start_hash,
        payload=directory._last_updated_partition_checkpoint_payload(config, initialized),
    )
    initialized.observe_count("root", directory.CountObservation.exact(1))
    resource_by_field = {"id": "affiliation", "resourceType": "OrganizationAffiliation"}
    for pass_number in (1, 2):
        initialized.record_pass("root", pass_number, [resource_by_field], complete=True)
    census = directory.LastUpdatedCompletenessCensus(1, 1, 1, 1)
    await _checkpoint(
        connection,
        old_schema,
        kind,
        old=True,
        count=2,
        start_hash=start_hash,
        payload=directory._last_updated_partition_checkpoint_payload(config, initialized, census),
    )
    await _checkpoint(connection, old_schema, "Location", old=True, count=1, start_hash="1" * 64)


async def _prepare_rows(connection, old_schema, new_schema, *, corrupt):
    await _prepare_checkpoint_fixture(connection, old_schema, new_schema)
    for resource_type, resource_id in (("Location", "location"), ("OrganizationAffiliation", "affiliation")):
        payload_by_field = {"id": resource_id}
        payload_hash = resource_payload_sha256_for_contract(
            payload_by_field, DEFAULT_RESOURCE_HASH_CONTRACT, resource_type=resource_type
        )
        await connection.execute(
            f"INSERT INTO {old_schema}.resource_input VALUES ($1,$2,$3,$4,$5::jsonb,NULL,5,0)",
            OLD_DATASET,
            resource_type,
            resource_id,
            payload_hash,
            json.dumps(payload_by_field),
        )
        descriptor, compressed = proof.build_dataset_proof_shard(
            [
                dict(
                    resource_type=resource_type,
                    resource_id=resource_id,
                    payload_hash=payload_hash,
                    payload_json=payload_by_field,
                )
            ],
            dataset_id=OLD_DATASET,
            endpoint_id="endpoint",
            acquisition_root_run_id=OLD_RUN,
            source_ids=SOURCE_IDS,
            resource_hash_contract=DEFAULT_RESOURCE_HASH_CONTRACT,
        )
        await proof._insert_dataset_proof_shard(
            connection,
            f"{old_schema}.{recovery._PROOF}",
            proof._proof_shard_insert_params(descriptor, compressed + b"x" if corrupt else compressed),
        )
    for pass_number in (1, 2):
        await connection.execute(
            f"INSERT INTO {old_schema}.resource_input VALUES ($1,$2,'affiliation',$3,'{{}}',NULL,5,$4)",
            OLD_DATASET,
            f"LU:OrganizationAffiliation:pass:{pass_number}",
            "1" * 64,
            pass_number,
        )
    await connection.execute(
        f"INSERT INTO {old_schema}.resource_input VALUES ($1,'Practitioner','incomplete',$2,'{{}}',NULL,5,3)",
        OLD_DATASET,
        "2" * 64,
    )


async def _prepare_run_catalog(connection, catalog):
    await connection.execute(f"CREATE SCHEMA {storage_identifier(catalog)}")
    run_table = storage_relation(catalog, "import_run")
    await connection.execute(f"""
        CREATE TABLE {run_table} (
            run_id text PRIMARY KEY, importer text, engine text, status text,
            started_at timestamp, finished_at timestamp, params jsonb
        )
    """)
    params = json.dumps(
        dict(
            provider_directory_endpoint_scope=BASE,
            source_ids=SOURCE_IDS,
            allow_retained_pagination_reset=False,
            full_refresh=True,
            import_resources=True,
        )
    )
    await connection.execute(
        f"INSERT INTO {run_table} VALUES "
        "($1,'provider-directory-fhir','healthcare-mrf-api','failed',now(),now(),$3::jsonb),"
        "($2,'provider-directory-fhir','healthcare-mrf-api','queued',NULL,NULL,$3::jsonb)",
        OLD_RUN,
        NEW_RUN,
        params,
    )


@pytest.mark.asyncio
@pytest.mark.parametrize("scenario", ["transfer", "corrupt", "practitioner_date_changed"])
async def test_carry_forward_complete_families_atomically(scenario):
    if not os.getenv(POSTGRES_DSN_ENV):
        pytest.skip("isolated PostgreSQL DSN required")
    url = make_url(os.environ[POSTGRES_DSN_ENV]).set(drivername="postgresql")
    connection = await asyncpg.connect(url.render_as_string(hide_password=False))
    tag = uuid4().hex[:12]
    catalog = f"fhir_test_{tag}_catalog"
    old = f"fhir_test_{tag}_old"
    new = f"fhir_test_{tag}_new"
    try:
        await _prepare_run_catalog(connection, catalog)
        old_schema = await _make_candidate(connection, catalog, old, run=OLD_RUN, dataset=OLD_DATASET, old=True)
        new_schema = await _make_candidate(connection, catalog, new, run=NEW_RUN, dataset=NEW_DATASET, old=False)
        await _prepare_rows(connection, old_schema, new_schema, corrupt=scenario == "corrupt")
        if scenario == "practitioner_date_changed":
            await _checkpoint(connection, old_schema, "Practitioner", old=True, count=1, start_hash="2" * 64)
        stopped = AsyncMock()
        scope_by_field = dict(
            catalog_schema=catalog,
            predecessor_schema=old,
            successor_schema=new,
            failed_run_id=OLD_RUN,
            successor_run_id=NEW_RUN,
            require_stopped=stopped,
        )
        if scenario != "transfer":
            error_class, reason = (
                (proof.ProviderDirectoryProofStoreError, "artifact changed")
                if scenario == "corrupt"
                else (ValueError, "recovery_practitioner_projection_changed")
            )
            async with connection.transaction(isolation="serializable"):
                with pytest.raises(error_class, match=reason):
                    await recovery.carry_forward_completed_fhir_inputs(connection, **scope_by_field)
        else:
            async with connection.transaction(isolation="serializable"):
                copied = await recovery.carry_forward_completed_fhir_inputs(connection, **scope_by_field)
            assert copied == {"Location": 1, "OrganizationAffiliation": 1}
            assert await connection.fetchval(f"SELECT sum(resource_count) FROM {new_schema}.{recovery._PROOF}") == 2
            assert (
                await connection.fetchval(
                    f"SELECT nextval(pg_get_serial_sequence('{new_schema}.resource_input','batch_ordinal'))"
                )
                == 6
            )
        assert stopped.await_count == 2
        assert await connection.fetchval(f"SELECT count(*) FROM {old_schema}.resource_input") == 5
        assert await connection.fetchval(f"SELECT count(*) FROM {new_schema}.resource_input") == (
            4 if scenario == "transfer" else 0
        )
        assert await connection.fetchval(
            f"SELECT count(*) FROM {new_schema}.{recovery._CHECKPOINT} WHERE state='complete'"
        ) == (2 if scenario == "transfer" else 0)
    finally:
        for schema in (new, old, catalog):
            await connection.execute(f"DROP SCHEMA IF EXISTS {storage_identifier(schema)} CASCADE")
        await connection.close()
