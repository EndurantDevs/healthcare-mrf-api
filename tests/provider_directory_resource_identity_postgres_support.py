@dataclass
class NativeResourceCandidate:
    component: object
    identity: dict
    binding: dict

    def transaction(self):
        """Use the existing genuine publisher login and original physical Owner."""
        return self.component.factory.transaction(self.component.database, isolation="read committed")

    async def load(self, resource_ids, resource_type="InsurancePlan"):
        async with self.transaction() as session:
            publisher = bound_publisher()
            receipt = self.binding["auxiliary"]["tables"][candidate.ROOT]
            async with candidate.bind_resource_identity_candidate(publisher, self.identity, receipt):
                return await bind_resource_identity_batch(
                    session, source_id="cms-npd", resource_type=resource_type, resource_ids=resource_ids
                )

    async def seal(self, *, include_entities=False):
        """Seal selected native identity families and recapture their complete layouts."""
        async with self.transaction():
            publisher = bound_publisher()
            previous = self.binding
            receipt = previous["auxiliary"]["tables"][candidate.ROOT]
            if include_entities:
                await entities.finish_identity_stages(
                    publisher, self.identity, auxiliary._cms_receipts(previous["auxiliary"]["tables"])
                )
            await candidate.finish_resource_identity_stage(publisher, self.identity, receipt)
            selected = previous["auxiliary"]["tables"] if include_entities else {candidate.ROOT: receipt}
            captured = await storage._capture(
                publisher.connection, publisher.policy, [value["name"] for value in selected.values()]
            )
            receipts_by_root = {
                **previous["auxiliary"]["tables"],
                **{root: captured[value["name"]] for root, value in selected.items()},
            }
            sealed_by_field = dict(
                phase="sealed",
                tables=receipts_by_root,
                sealed_sha256=auxiliary._seal_digest(self.identity, receipts_by_root),
            )
            updated_by_field = {**previous, "auxiliary": sealed_by_field}
            await storage._store(publisher.connection, publisher.policy, self.identity, previous, updated_by_field)
        self.binding = updated_by_field

    async def publish(self, *, include_entities=False):
        async with self.transaction():
            if include_entities:
                await auxiliary.publish_identity_candidate(bound_publisher(), self.binding)
                return
            await candidate.publish_resource_identity_stage(
                bound_publisher(), self.identity, self.binding["auxiliary"]["tables"][candidate.ROOT]
            )


async def prepare_resource_candidate(
    component, resource_ids, *, resource_type="InsurancePlan", release_id="a" * 64, resources=None
):
    """Create closed Owner heaps and a protected header for identity components.

    Exact payloads also support CMS entities; complete SOURCE admission and
    publication are not attested by this component fixture.
    """
    dataset = "identity-" + uuid4().hex
    identity = _identity(component.policy.schema, dataset)
    identity["metadata"]["source_release"]["vector_sha256"] = release_id
    fixture = NativeResourceCandidate(component, identity, {})
    async with fixture.transaction():
        publisher = bound_publisher()
        connection, policy = publisher.connection, publisher.policy
        prefix = "pdgs_" + uuid4().hex
        names_by_root = {root: prefix + "_" + storage._SUFFIXES[root] for root in storage.RELATIONS}
        names_by_root.update(resource_input=prefix + "_ri", witness_input=prefix + "_wi")
        for key, name in names_by_root.items():
            root = storage.RESOURCE if key == "resource_input" else storage.WITNESS if key == "witness_input" else key
            if key in {"resource_input", "witness_input"}:
                identity_clause = " GENERATED BY DEFAULT AS IDENTITY" if key == "resource_input" else ""
                layout = (
                    f"LIKE {storage_relation(policy.schema, root)} INCLUDING STORAGE, "
                    f"batch_ordinal bigint{identity_clause} NOT NULL, row_ordinal integer NOT NULL"
                )
            else:
                layout = f"LIKE {storage_relation(policy.schema, root)} INCLUDING DEFAULTS INCLUDING CONSTRAINTS"
            await connection.execute(f"CREATE TABLE {storage_relation(policy.schema, name)} ({layout})")
            await storage._close_grants(connection, policy, name)
            if key == "resource_input":
                sequence_name = await connection.fetchval(
                    "SELECT c.relname FROM pg_class c WHERE c.oid=pg_get_serial_sequence($1,'batch_ordinal')::regclass",
                    storage_relation(policy.schema, name),
                )
                await storage._close_grants(connection, policy, sequence_name, sequence=True)
        captured = await storage._capture(connection, policy, list(names_by_root.values()))
        binding_by_field = dict(
            contract=storage.CONTRACT,
            identity=identity,
            phase="prepared",
            ordinal=0,
            resets={},
            tables={key: captured[name] for key, name in names_by_root.items()},
            auxiliary=await auxiliary.prepare_identity_candidate(publisher, identity, prefix),
            relationship_sha256=None,
        )
        await _store_header(connection, policy.schema, identity, binding_by_field)
        await _copy_witness(
            connection,
            policy.schema,
            names_by_root[storage.WITNESS],
            dataset,
            resource_type,
            resource_ids,
            release_id=release_id,
            resources=resources,
        )
    fixture.binding = binding_by_field
    return fixture


def _identity(schema, dataset):
    return dict(
        dataset_id=dataset,
        endpoint_id=dataset,
        acquisition_root_run_id=dataset,
        metadata=dict(
            source_ids=["cms-npd"],
            source_release=dict(source_id="cms-npd", vector_sha256="a" * 64),
            network_bindings=dict(
                source_system="fhir",
                source_id="cms-npd",
                dataset_schema=schema,
                dataset_id=dataset,
                edition_id=dataset,
                producer_id="cms-npd-bulk-fhir-v1",
                alias_scope="cms-npd",
                source_key_kind="organization_resource_id",
            ),
        ),
    )


async def _store_header(connection, schema, identity, binding):
    endpoint = storage_relation(schema, "provider_directory_api_endpoint")
    header = storage_relation(schema, storage.HEADER)
    await connection.execute(
        f"INSERT INTO {endpoint}(endpoint_id,canonical_api_base,credential_descriptor_hash,endpoint_signature_hash) "
        "VALUES($1,$2,$3,$3)",
        identity["endpoint_id"],
        "https://example.invalid/" + identity["endpoint_id"],
        "a" * 64,
    )
    await connection.execute(
        f"INSERT INTO {header}(dataset_id,endpoint_id,acquisition_root_run_id,status,is_current,resource_count,"
        "publication_metadata_json,candidate_storage_json) VALUES($1,$1,$1,'acquiring',false,0,$2::jsonb,$3::jsonb)",
        identity["dataset_id"],
        storage._encoded(identity["metadata"]),
        storage._encoded(binding),
    )


async def _copy_witness(
    connection, schema, name, dataset, resource_type, resource_ids, *, release_id="a" * 64, resources=None
):
    records = []
    for key in sorted(set(resource_ids)):
        resource = {"resourceType": resource_type, "id": key} if resources is None else resources[key]
        raw = json.dumps(resource, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False)
        digest = hashlib.sha256(raw.encode()).hexdigest()
        records.append((dataset, "cms-npd", release_id, resource_type, key, digest, digest, raw))
    await connection.copy_records_to_table(name, schema_name=schema, columns=WITNESS_COLUMNS, records=records)
