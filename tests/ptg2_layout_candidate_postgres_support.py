async def _insert_v4_cleanup_winner(
    session,
    schema: str,
    generation: str,
) -> int:
    winner_key = await session.scalar(
        text(
            f"""
            INSERT INTO {schema}.ptg2_v3_snapshot_layout
                (build_token, generation, state, mapping_digest,
                 support_digest, lease_until, published_at)
            VALUES ('v4-winner', :generation, 'sealed', :mapping_digest,
                    :support_digest,
                    transaction_timestamp() + INTERVAL '6 hours',
                    transaction_timestamp())
            RETURNING snapshot_key
            """
        ),
        {
            "generation": generation,
            "mapping_digest": b"m" * 32,
            "support_digest": b"s" * 32,
        },
    )
    return int(winner_key)


async def seed_v4_duplicate_cleanup_pair(
    sessions,
    schema: str,
    *,
    generation: str,
) -> tuple[int, int]:
    """Seed one sealed winner and one dense, unbound V4 loser candidate."""

    fingerprint = b"v" * 32
    async with sessions.begin() as session:
        winner_key = await _insert_v4_cleanup_winner(
            session,
            schema,
            generation,
        )
        loser_key = await session.scalar(
            text(
                f"""
                INSERT INTO {schema}.ptg2_v3_snapshot_layout
                    (build_token, generation, state, lease_until)
                VALUES ('v4-loser', :generation, 'building',
                        transaction_timestamp() + INTERVAL '6 hours')
                RETURNING snapshot_key
                """
            ),
            {"generation": generation},
        )
        await session.execute(
            text(
                f"INSERT INTO {schema}.ptg2_v3_layout_fingerprint "
                "(semantic_fingerprint, snapshot_key) "
                "VALUES (:fingerprint, :snapshot_key)"
            ),
            {"fingerprint": fingerprint, "snapshot_key": winner_key},
        )
        await session.execute(
            text(
                f"INSERT INTO {schema}.ptg2_layout_build_candidate "
                "(snapshot_key, semantic_fingerprint) "
                "VALUES (:snapshot_key, :fingerprint)"
            ),
            {"snapshot_key": loser_key, "fingerprint": fingerprint},
        )
        await session.execute(
            text(
                f'INSERT INTO {schema}."{PTG2_V3_DENSE_LAYOUT_TABLES[0]}" '
                "(snapshot_key) SELECT :snapshot_key FROM generate_series(1, 3)"
            ),
            {"snapshot_key": loser_key},
        )
    return int(loser_key), int(winner_key)


async def _release_v4_cleanup_batch(
    sessions,
    schema_name: str,
    schema: str,
    loser_key: int,
):
    async with sessions.begin() as session:
        stats = await ptg2_shared_gc._release_layouts_ready(
            _SessionExecutor(session),
            schema_name=schema_name,
            building_max_age_seconds=21_600,
            grace_seconds=0,
            max_layouts=1,
            layout_keys=(loser_key,),
            dense_batch_rows=1,
        )
    async with sessions() as observer:
        remaining_rows = await observer.scalar(
            text(
                f'SELECT COUNT(*) FROM {schema}."'
                f'{PTG2_V3_DENSE_LAYOUT_TABLES[0]}" '
                "WHERE snapshot_key = :snapshot_key"
            ),
            {"snapshot_key": loser_key},
        )
    return stats, int(remaining_rows)


async def verify_v4_cleanup_replay(
    sessions,
    schema_name: str,
    schema: str,
    loser_key: int,
    winner_key: int,
) -> None:
    """Prove bounded cleanup commits progress and exact-replays to zero."""

    logical_counts: list[int] = []
    remaining_counts: list[int] = []
    for _attempt in range(3):
        stats, remaining = await _release_v4_cleanup_batch(
            sessions,
            schema_name,
            schema,
            loser_key,
        )
        logical_counts.append(stats.logical_layout_count)
        remaining_counts.append(remaining)
    replay_stats, _remaining = await _release_v4_cleanup_batch(
        sessions,
        schema_name,
        schema,
        loser_key,
    )
    assert logical_counts == [0, 0, 1]
    assert remaining_counts == [2, 1, 0]
    assert replay_stats.logical_layout_count == 0
    async with sessions() as observer:
        surviving_keys = tuple(
            (await observer.scalars(
                text(
                    f"SELECT snapshot_key FROM {schema}.ptg2_v3_snapshot_layout "
                    "ORDER BY snapshot_key"
                )
            )).all()
        )
    assert surviving_keys == (winner_key,)


