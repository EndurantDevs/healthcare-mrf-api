async def upgrade_and_assert_live_candidate_adoption(
    connection,
    schema: str,
    migration,
    statements: list[str],
) -> None:
    """Apply the migration and verify old and newly-triggered adoption."""
    migration.upgrade()
    for statement in statements:
        await connection.execute(statement)
    adopted = await connection.fetchrow(
        f"SELECT candidate.snapshot_key, "
        f"encode(candidate.semantic_fingerprint, 'hex') AS fingerprint, "
        f"EXISTS (SELECT 1 FROM {schema}.ptg2_v3_layout_fingerprint "
        f"WHERE snapshot_key = candidate.snapshot_key) AS legacy_index_retained "
        f"FROM {schema}.ptg2_layout_build_candidate AS candidate"
    )
    assert dict(adopted) == {
        "snapshot_key": 41,
        "fingerprint": "41" * 32,
        "legacy_index_retained": True,
    }
    await connection.execute(
        f"INSERT INTO {schema}.ptg2_v3_snapshot_layout "
        f"(snapshot_key, build_token, generation, state, lease_until) "
        f"VALUES (42, 'old-after-upgrade', 'shared_blocks_v3', 'building', "
        f"transaction_timestamp() + INTERVAL '6 hours'); "
        f"INSERT INTO {schema}.ptg2_v3_layout_fingerprint "
        f"(semantic_fingerprint, snapshot_key) "
        f"VALUES (decode(repeat('42', 32), 'hex'), 42);"
    )
    assert await connection.fetchval(
        f"SELECT COUNT(*) FROM {schema}.ptg2_layout_build_candidate "
        f"WHERE snapshot_key = 42 "
        f"AND semantic_fingerprint = decode(repeat('42', 32), 'hex') "
        f"AND cleanup_pending_at IS NULL"
    ) == 1
    await connection.execute(
        f"DELETE FROM {schema}.ptg2_v3_snapshot_layout WHERE snapshot_key = 42"
    )


async def assert_migration_candidate_cleanup(
    connection,
    schema: str,
    canonical_snapshot_key: int,
) -> None:
    """Assert the old candidate durably targets the canonical winner."""
    cleanup = await connection.fetchrow(
        f"SELECT cleanup_pending_at IS NOT NULL AS cleanup_pending, "
        f"canonical_snapshot_key FROM {schema}.ptg2_layout_build_candidate "
        f"WHERE snapshot_key = 41"
    )
    assert dict(cleanup) == {
        "cleanup_pending": True,
        "canonical_snapshot_key": canonical_snapshot_key,
    }
    assert await connection.fetchval(
        f"SELECT COUNT(*) FROM {schema}.ptg2_v3_layout_fingerprint"
    ) == 1


async def assert_candidate_migration_downgrade(
    connection,
    schema_name: str,
    migration,
    statements: list[str],
) -> None:
    """Drain adopted candidates, then verify the exact-empty downgrade."""
    await connection.execute(
        f'DELETE FROM "{schema_name}".ptg2_layout_build_candidate'
    )
    downgrade_offset = len(statements)
    migration.downgrade()
    for statement in statements[downgrade_offset:]:
        await connection.execute(statement)
    assert await connection.fetchval(
        "SELECT to_regclass($1)",
        f"{schema_name}.ptg2_layout_build_candidate",
    ) is None
    assert await connection.fetchval(
        "SELECT COUNT(*) FROM pg_proc AS procedure "
        "JOIN pg_namespace AS namespace "
        "ON namespace.oid = procedure.pronamespace "
        "WHERE namespace.nspname = $1 "
        "AND procedure.proname = "
        "'ptg2_capture_building_layout_fingerprint'",
        schema_name,
    ) == 0
